/**
 * PenPaper service worker.
 *
 * The board is local-first: the shell is the only thing the network provides,
 * and everything the user draws lives in IndexedDB. So this worker keeps two
 * promises and nothing more:
 *
 *   1. Navigation is network-first, with the offline board as the fallback.
 *   2. Hashed `/_next/static` assets and icons are cache-first and immutable.
 *
 * Install also reads the rendered offline board and caches the chunks named in
 * its HTML. Without that step the first visit would be uncached — the worker
 * only starts controlling after hydration, by which point every script has
 * already loaded — and a user who goes offline before the second visit would
 * get HTML with no JavaScript behind it.
 *
 * RSC payloads (`?_rsc=`) and API traffic are deliberately not cached. Caching
 * a client-navigation fragment can serve a board from a different route, and
 * the collaborative socket in Phase 3 must never see a stale response.
 */

const VERSION = "penpaper-v2";
const PRECACHE = `${VERSION}-core`;
const RUNTIME = `${VERSION}-runtime`;

const CORE = [
  "/b/local",
  "/manifest.webmanifest",
  "/icons/icon-180.png",
  "/icons/icon-192.png",
  "/icons/icon-512.png",
];

self.addEventListener("install", (event) => {
  event.waitUntil(
    (async () => {
      // One missing URL (a redirect, a renamed asset) must not fail the whole
      // install and leave the app permanently un-installable.
      await Promise.allSettled(
        CORE.map((url) => caches.open(PRECACHE).then((cache) => cache.add(url))),
      );
      await precacheOfflineShell();
      await self.skipWaiting();
    })(),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      const keys = await caches.keys();
      await Promise.all(
        keys
          .filter((key) => key.startsWith("penpaper-") && !key.startsWith(VERSION))
          .map((key) => caches.delete(key)),
      );
      await self.clients.claim();
    })(),
  );
});

self.addEventListener("fetch", (event) => {
  const { request } = event;

  if (request.method !== "GET") return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === "navigate") {
    event.respondWith(networkFirst(request));
    return;
  }

  // Next.js content-hashes these files, so a cached copy is always correct.
  if (url.pathname.startsWith("/_next/static/") || url.pathname.startsWith("/icons/")) {
    event.respondWith(cacheFirst(request));
    return;
  }

  if (url.pathname === "/manifest.webmanifest") {
    event.respondWith(staleWhileRevalidate(request));
    return;
  }
});

/** Fetches the offline board once, then caches its scripts and stylesheets. */
async function precacheOfflineShell() {
  const response = await fetch("/b/offline", { cache: "reload" });
  if (!response.ok) return;

  const core = await caches.open(PRECACHE);
  await core.put("/b/offline", response.clone());

  const html = await response.text();
  const runtime = await caches.open(RUNTIME);
  const assets = new Set();

  // The HTML is generated by Next, so this only has to recognise its own
  // `src`/`href` attributes; it is not a general-purpose HTML parser.
  for (const match of html.matchAll(/(?:src|href)="(\/_next\/static\/[^"]+)"/g)) {
    assets.add(match[1]);
  }

  await Promise.allSettled([...assets].map((url) => runtime.add(url)));
}

async function networkFirst(request) {
  const cache = await caches.open(RUNTIME);

  try {
    const response = await fetch(request);
    // Only complete, non-opaque responses are safe to replay later.
    if (response.ok && response.type === "basic") {
      cache.put(request, response.clone());
    }
    return response;
  } catch {
    const cached =
      (await cache.match(request, { ignoreSearch: true })) ??
      (await caches.match(request, { ignoreSearch: true }));
    if (cached) return cached;

    const core = await caches.open(PRECACHE);
    return (await core.match("/b/offline")) ?? (await core.match("/b/local")) ?? Response.error();
  }
}

async function cacheFirst(request) {
  const cached = await caches.match(request);
  if (cached) return cached;

  const cache = await caches.open(RUNTIME);
  const response = await fetch(request);
  if (response.ok) cache.put(request, response.clone());
  return response;
}

async function staleWhileRevalidate(request) {
  const cache = await caches.open(RUNTIME);
  const cached = await cache.match(request);

  const network = fetch(request)
    .then((response) => {
      if (response.ok) cache.put(request, response.clone());
      return response;
    })
    .catch(() => null);

  return cached ?? (await network) ?? Response.error();
}
